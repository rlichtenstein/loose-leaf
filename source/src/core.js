function buildWorld(rooms) {
  rooms = rooms || ROOMS;
  let GW = 0, GH = 0;
  for (const r of rooms) { GW = Math.max(GW, r.cx + r.cw); GH = Math.max(GH, r.cy + r.ch); }
  const W = GW * RW, H = GH * RH;
  const tiles = new Uint8Array(W * H).fill(1);
  const cellRoom = new Int8Array(GW * GH).fill(-1);
  const ents = []; let scrapN = 0, bookN = 0, start = null;
  rooms.forEach((r, ri) => {
    const rw = r.cw * RW, rh = r.ch * RH;
    if (r.map.length !== rh) throw new Error(`room ${r.id}: ${r.map.length} rows, expected ${rh}`);
    r.x0 = r.cx * RW; r.y0 = r.cy * RH; r.tw = rw; r.th = rh;
    r.px = r.x0 * T; r.py = r.y0 * T; r.pw = rw * T; r.ph = rh * T;
    for (let y = 0; y < r.ch; y++) for (let x = 0; x < r.cw; x++) {
      const ci = (r.cy + y) * GW + r.cx + x;
      if (cellRoom[ci] !== -1) throw new Error(`cell overlap at room ${r.id}`);
      cellRoom[ci] = ri;
    }
    r.map.forEach((row, y) => {
      if (row.length !== rw) throw new Error(`room ${r.id} row ${y}: length ${row.length}, expected ${rw}`);
      for (let x = 0; x < rw; x++) {
        const c = row[x], tx = r.x0 + x, ty = r.y0 + y, i = ty * W + tx;
        if (CHAR_TILE[c] !== undefined) { tiles[i] = CHAR_TILE[c]; continue; }
        tiles[i] = 0;
        const px = tx * T, py = ty * T;
        if (c === '.') continue;
        if (c === '@') start = { x: px + 2, y: py + 2 };
        else if (c === '*') ents.push({ k: 'scrap', id: scrapN++, x: px + 2, y: py + 2, w: 12, h: 12, room: ri });
        else if (POWER_OF[c]) ents.push({ k: 'power', pw: POWER_OF[c], x: px + 1, y: py + 1, w: 14, h: 14, room: ri });
        else if (DOOR_CH.includes(c)) ents.push({ k: 'door', ch: c, x: px + 2, y: py - 14, w: 12, h: 30, room: ri });
        else if (c === 'm') ents.push({ k: 'bolt', x: px + 2, y: py + 2, w: 12, h: 12, room: ri });
        else if (POT_OF[c]) ents.push({ k: 'pot', color: POT_OF[c], x: px + 1, y: py + 1, w: 14, h: 14, room: ri });
        else if (c === 'k') ents.push({ k: 'book', id: bookN++, x: px + 3, y: py - 16, w: 10, h: 32, room: ri, sx: px + 2, sy: py + 2 });
        else if (c === 'c') ents.push({ k: 'enemy', type: 'crawl', x: px + 2, y: py + 8, w: 12, h: 8, room: ri });
        else if (c === 'o') ents.push({ k: 'enemy', type: 'bobV', x: px + 3, y: py + 3, w: 10, h: 10, room: ri });
        else if (c === 'h') ents.push({ k: 'enemy', type: 'bobH', x: px + 3, y: py + 3, w: 10, h: 10, room: ri });
        else throw new Error(`room ${r.id}: unknown map character "${c}"`);
      }
    });
  });
  const byRoom = rooms.map((_, ri) => ents.filter(e => e.room === ri));
  const bolts = ents.filter(e => e.k === 'bolt'), doors = ents.filter(e => e.k === 'door');
  for (const d of doors) d.to = doors.find(o => o !== d && o.ch === d.ch) || null;
  return { W, H, GW, GH, tiles, cellRoom, rooms, ents, byRoom, bolts, doors, start, scrapN, bookN };
}

/* ---------- state ---------- */
function newPlayer() {
  return { x: 0, y: 0, w: PH.PW, h: PH.PHT, vx: 0, vy: 0, face: 1, onGround: false, gk: '', coyote: 0, jumpBuf: 0, jumpHeld: false,
    dashT: 0, dashDir: 1, dashCD: 0, airDash: true, pencil: true, eraseT: 0, eraseCD: 0,
    wallDir: 0, clingT: 0, wallCoyote: 0, lastWall: 0, kickT: 0, glide: false, color: 0,
    zipB: null, hangB: null, zipT: 0, boltCD: 0, lastBolt: null, doorLock: null, bounce: 0, groundT: 99, bounceOK: false, soaked: false,
    hp: PH.MAXHP, maxHp: PH.MAXHP, inv: 0, kb: 0, safeX: 0, safeY: 0, landT: 0 };
}

function newState(world, save, powers) {
  const s = {
    world, tiles: world.tiles.slice(), layer: 0,
    powers: Object.fromEntries(ALL_POWERS.map(k => [k, false])),
    got: new Set(), broken: [], book: -1, explored: new Set(),
    frame: 0, time: 0, deaths: 0, events: [], plats: [], enemies: [], room: -1,
    dead: 0, freeze: 0, won: false, done: false, noEnemies: false, p: newPlayer(),
  };
  if (save) applySave(s, save);
  if (powers) for (const k of ALL_POWERS) s.powers[k] = !!powers[k];
  if (s.layer === 1 && !s.powers.flip) s.layer = 0;
  respawn(s);
  return s;
}

function applySave(s, d) {
  try {
    for (const k of Object.keys(s.powers)) s.powers[k] = !!(d.powers && d.powers[k]);
    s.got = new Set(d.got || []);
    s.broken = (d.broken || []).filter(i => Number.isInteger(i) && i >= 0 && i < s.tiles.length);
    for (const i of s.broken) s.tiles[i] = 0;
    s.book = Number.isInteger(d.book) ? d.book : -1;
    s.layer = d.layer === 1 && s.powers.flip ? 1 : 0;
    s.explored = new Set(d.explored || []);
    s.time = d.time || 0; s.deaths = d.deaths || 0;
    s.done = !!d.done;
  } catch (e) { /* a broken save starts a fresh game */ }
}

function makeSave(s) {
  return { v: 1, powers: { ...s.powers }, got: [...s.got], broken: s.broken.slice(), book: s.book, layer: s.layer,
    explored: [...s.explored], time: s.time, deaths: s.deaths, done: s.done };
}

function scrapCount(s) { let n = 0; for (const k of s.got) if (/^s\d+$/.test(k)) n++; return n; } // 'spring' is a tool, not a scrap

function ev(s, type, data) { s.events.push({ type, data }); }

function respawn(s) {
  const p = s.p, w = s.world;
  let sp = w.start;
  if (s.book >= 0) { const b = w.ents.find(e => e.k === 'book' && e.id === s.book); if (b) sp = { x: b.sx, y: b.sy }; }
  p.x = sp.x; p.y = sp.y; p.vx = p.vy = 0; p.hp = p.maxHp; p.dashT = 0; p.eraseT = 0; p.inv = 0; p.kb = 0;
  p.safeX = p.x; p.safeY = p.y; p.onGround = false; p.jumpBuf = 0; p.pencil = true; p.airDash = true;
  p.wallDir = 0; p.clingT = 0; p.wallCoyote = 0; p.kickT = 0; p.glide = false; p.color = 0;
  p.zipB = null; p.hangB = null; p.zipT = 0; p.boltCD = 0; p.lastBolt = null; p.doorLock = null; p.bounce = 0; p.groundT = 99; p.bounceOK = false;
  // never respawn inside a layer block
  if (overlapsCode(s, p.x, p.y, p.w, p.h, s.layer === 0 ? TL.LA : TL.LB)) s.layer = 1 - s.layer;
  s.plats.length = 0; s.room = -1; trackRoom(s);
}

/* ---------- tiles ---------- */
function tileAt(s, tx, ty) {
  const w = s.world;
  if (tx < 0 || tx >= w.W || ty < 0) return TL.SOLID;
  if (ty >= w.H) return TL.EMPTY;
  return s.tiles[ty * w.W + tx];
}
function solidCode(s, c) {
  if (c >= TL.PO && c <= TL.PV) return !(s.powers.brush && s.p.color === c - TL.PO + 1);
  return c === TL.SOLID || c === TL.GLOSS || c === TL.ICE || c === TL.SCRIBBLE || c === TL.PERF || (c === TL.LA && s.layer === 0) || (c === TL.LB && s.layer === 1);
}
function overlapsCode(s, x, y, w, h, code) {
  const tx0 = Math.floor(x / T), tx1 = Math.floor((x + w - 0.001) / T), ty0 = Math.floor(y / T), ty1 = Math.floor((y + h - 0.001) / T);
  for (let ty = ty0; ty <= ty1; ty++) for (let tx = tx0; tx <= tx1; tx++) if (tileAt(s, tx, ty) === code) return true;
  return false;
}
function rectSolid(s, x, y, w, h) {
  const tx0 = Math.floor(x / T), tx1 = Math.floor((x + w - 0.001) / T), ty0 = Math.floor(y / T), ty1 = Math.floor((y + h - 0.001) / T);
  for (let ty = ty0; ty <= ty1; ty++) for (let tx = tx0; tx <= tx1; tx++) if (solidCode(s, tileAt(s, tx, ty))) return true;
  return false;
}
function breakGroup(s, tx, ty, code) {
  const w = s.world, cells = [], stack = [[tx, ty]];
  while (stack.length) {
    const [x, y] = stack.pop();
    if (x < 0 || y < 0 || x >= w.W || y >= w.H) continue;
    const i = y * w.W + x;
    if (s.tiles[i] !== code) continue;
    s.tiles[i] = 0; s.broken.push(i); cells.push([x, y]);
    stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
  }
  if (cells.length) ev(s, 'break', { code, cells });
  return cells.length;
}

/* ---------- movement ---------- */
function moveX(s, dx) {
  const p = s.p; if (!dx) return false;
  let nx = p.x + dx;
  const ty0 = Math.floor(p.y / T), ty1 = Math.floor((p.y + p.h - 0.001) / T);
  const tx = dx > 0 ? Math.floor((nx + p.w - 0.001) / T) : Math.floor(nx / T);
  let hit = false;
  for (let ty = ty0; ty <= ty1; ty++) {
    let c = tileAt(s, tx, ty);
    if (c === TL.PERF && p.dashT > 0) { breakGroup(s, tx, ty, TL.PERF); c = 0; }
    if (solidCode(s, c)) hit = true;
  }
  if (hit) { nx = dx > 0 ? tx * T - p.w : (tx + 1) * T; p.vx = 0; }
  p.x = nx; return hit;
}

function moveY(s, dy) {
  const p = s.p;
  const tx0 = Math.floor(p.x / T), tx1 = Math.floor((p.x + p.w - 0.001) / T);
  let ny = p.y + dy, landed = false, gk = '';
  if (dy > 0) {
    const oldB = p.y + p.h, newB = ny + p.h;
    const ty = Math.floor((newB - 0.001) / T);
    let best = Infinity;
    for (let tx = tx0; tx <= tx1; tx++) {
      const c = tileAt(s, tx, ty);
      if (solidCode(s, c) || (c === TL.ONEWAY && oldB <= ty * T + 0.01)) { best = ty * T; gk = 'tile'; }
    }
    for (const pl of s.plats) {
      if (p.x < pl.x + pl.w && p.x + p.w > pl.x && oldB <= pl.y + 0.01 && newB >= pl.y && pl.y < best) { best = pl.y; gk = 'plat'; }
    }
    if (best !== Infinity) { ny = best - p.h; landed = true; p.vy = 0; }
  } else if (dy < 0) {
    const ty = Math.floor(ny / T);
    for (let tx = tx0; tx <= tx1; tx++) if (solidCode(s, tileAt(s, tx, ty))) { ny = (ty + 1) * T; p.vy = 0; p.jumpHeld = false; ev(s, 'bonk'); break; }
  } else {
    // probe for ground while the vertical speed is zero (dashing)
    const b = p.y + p.h, ty = Math.floor((b + 0.5) / T);
    if (Math.abs(b - ty * T) < 0.02) for (let tx = tx0; tx <= tx1; tx++) {
      const c = tileAt(s, tx, ty); if (solidCode(s, c) || c === TL.ONEWAY) { landed = true; gk = 'tile'; }
    }
    if (!landed) for (const pl of s.plats) if (p.x < pl.x + pl.w && p.x + p.w > pl.x && Math.abs(b - pl.y) < 0.02) { landed = true; gk = 'plat'; }
  }
  p.y = ny; p.onGround = landed; p.gk = gk;
}

/* standing only on things you can drop through: one-way ledges or a pencil line (nothing solid underfoot) */
function onOneWay(s) {
  const p = s.p;
  if (!p.onGround) return false;
  if (p.gk === 'plat') return true;
  const ty = Math.floor((p.y + p.h + 0.5) / T); let any = false;
  for (let tx = Math.floor(p.x / T); tx <= Math.floor((p.x + p.w - 0.001) / T); tx++) {
    const c = tileAt(s, tx, ty);
    if (solidCode(s, c)) return false;
    if (c === TL.ONEWAY) any = true;
  }
  return any;
}

/* sticky tape: is there a wall the tape can grab right beside the doodle? */
function wallAt(s, side) {
  const p = s.p, probe = side > 0 ? p.x + p.w + 0.5 : p.x - 0.5, tx = Math.floor(probe / T);
  if (side > 0 ? tx * T - (p.x + p.w) > 0.6 : p.x - (tx + 1) * T > 0.6) return false;
  const c = tileAt(s, tx, Math.floor((p.y + p.h / 2) / T));
  return c !== TL.GLOSS && c !== TL.ICE && solidCode(s, c);
}

function eraseBox(p) {
  return { x: p.face > 0 ? p.x + p.w : p.x - PH.ERASE_W, y: p.y + 1, w: PH.ERASE_W, h: PH.ERASE_H };
}
function hurtBox(e) { return { x: e.x + 1, y: e.y + 1, w: e.w - 2, h: e.h - 2 }; }
function spikeBox(tx, ty) { return { x: tx * T + 2, y: ty * T + 9, w: 12, h: 7 }; }
function hit(a, b) { return a.x < b.x + b.w && a.x + a.w > b.x && a.y < b.y + b.h && a.y + a.h > b.y; }

function roomAt(s, px, py) {
  const w = s.world, cx = Math.floor(px / (RW * T)), cy = Math.floor(py / (RH * T));
  if (cx < 0 || cy < 0 || cx >= w.GW || cy >= w.GH) return -1;
  return w.cellRoom[cy * w.GW + cx];
}
function trackRoom(s) {
  const p = s.p, r = roomAt(s, p.x + p.w / 2, p.y + p.h / 2);
  if (r >= 0 && r !== s.room) { s.room = r; s.explored.add(r); spawnEnemies(s); ev(s, 'room', r); }
}
function spawnEnemies(s) {
  if (s.noEnemies) { s.enemies = []; return; }
  s.enemies = s.world.byRoom[s.room].filter(e => e.k === 'enemy')
    .map((e, i) => ({ type: e.type, x: e.x, y: e.y, w: e.w, h: e.h, bx: e.x, by: e.y, vx: -0.45, t: i * 37, gone: false, squish: 0 }));
}

function updEnemies(s) {
  for (const e of s.enemies) {
    if (e.gone) { if (e.squish > 0) e.squish--; continue; }
    e.t++;
    if (e.type === 'crawl') {
      const front = e.vx > 0 ? e.x + e.w + e.vx : e.x + e.vx;
      const col = Math.floor(front / T), row = Math.floor((e.y + e.h - 1) / T);
      const wall = solidCode(s, tileAt(s, col, row));
      const g = tileAt(s, col, row + 1), ground = solidCode(s, g) || g === TL.ONEWAY;
      if (wall || !ground) e.vx = -e.vx; else e.x += e.vx;
    } else if (e.type === 'bobV') {
      e.y = e.by + Math.sin(e.t * 0.035) * 20;
    } else if (e.type === 'bobH') {
      e.x = e.bx + Math.sin(e.t * 0.028) * 30;
    }
  }
}

function hurt(s, fromX) {
  const p = s.p;
  p.zipB = null; p.hangB = null;
  p.hp--; p.inv = PH.INV; ev(s, 'hurt');
  if (p.hp <= 0) { die(s); return; }
  p.kb = PH.KB; p.dashT = 0; p.eraseT = 0;
  p.vx = (p.x + p.w / 2 < fromX ? -1 : 1) * 2.2; p.vy = -3.2; p.jumpHeld = false;
}
function die(s) { s.dead = 70; s.deaths++; ev(s, 'die'); }
function hazard(s) {
  const p = s.p;
  if (p.inv === 0) { p.hp--; p.inv = PH.INV; }
  ev(s, 'spike');
  if (p.hp <= 0) { die(s); return; }
  s.freeze = 28; p.dashT = 0; p.vx = 0; p.vy = 0; p.zipB = null; p.hangB = null;
}

function tryFlip(s) {
  const p = s.p, nl = 1 - s.layer, code = nl === 0 ? TL.LA : TL.LB;
  if (overlapsCode(s, p.x, p.y, p.w, p.h, code)) { ev(s, 'flipFail'); return false; }
  s.layer = nl; ev(s, 'flip', nl); return true;
}

function updateSafe(s) {
  const p = s.p;
  if (!(p.onGround && p.gk === 'tile' && p.dashT === 0 && p.kb === 0)) return;
  const by = Math.floor((p.y + p.h + 1) / T);
  const l = tileAt(s, Math.floor(p.x / T), by), r = tileAt(s, Math.floor((p.x + p.w - 0.001) / T), by);
  const ok = c => c === TL.SOLID || c === TL.ONEWAY || c === TL.GLOSS || c === TL.ICE;
  if (ok(l) && ok(r) && !overlapsCode(s, p.x - 4, p.y, p.w + 8, p.h, TL.SPIKE)) { p.safeX = p.x; p.safeY = p.y; }
}

/* fridge magnet: the bolt it would zip to right now (prefers bolts above you, then ones you face) */
function lineClear(s, x0, y0, x1, y1) {
  const n = Math.ceil(Math.hypot(x1 - x0, y1 - y0) / 4);
  for (let i = 1; i < n; i++) {
    const t = i / n, c = tileAt(s, Math.floor((x0 + (x1 - x0) * t) / T), Math.floor((y0 + (y1 - y0) * t) / T));
    if (solidCode(s, c)) return false;
  }
  return true;
}
function pickBolt(s, face, exclude) {
  const p = s.p, cx = p.x + p.w / 2, cy = p.y + p.h / 2;
  let best = null, bestScore = Infinity;
  for (const b of s.world.bolts) {
    if (b === exclude || (b === p.lastBolt && p.boltCD > 0)) continue;
    const bx = b.x + b.w / 2, by = b.y + b.h / 2, d = Math.hypot(bx - cx, by - cy);
    if (d > PH.ZIP_R || !lineClear(s, cx, cy, bx, by)) continue;
    const score = (by - cy > 10 ? 10000 : 0) + ((bx - cx) * face < -6 ? 1000 : 0) + d;
    if (score < bestScore) { bestScore = score; best = b; }
  }
  return best;
}
/* returns true when the magnet moved the doodle this tick (zipping or hanging) */
function magnet(s, inp, dir) {
  const p = s.p;
  if (!s.powers.magnet) return false;
  if (p.boltCD > 0) p.boltCD--;
  if (inp.dash && p.kb === 0) {
    const b = pickBolt(s, dir || p.face, p.hangB || p.zipB);
    if (b) {
      if (p.hangB) { p.lastBolt = p.hangB; p.boltCD = PH.BOLT_CD; }
      p.zipB = b; p.hangB = null; p.zipT = PH.ZIP_T; p.dashT = 0; p.glide = false; p.wallDir = 0; p.kickT = 0;
      p.vx = p.vy = 0; p.jumpHeld = false; p.coyote = 0; inp.dash = 0; ev(s, 'zip');
    }
  }
  if (p.hangB) {
    if (p.jumpBuf > 0 && p.kb === 0) {
      p.lastBolt = p.hangB; p.boltCD = PH.BOLT_CD; p.hangB = null;
      p.vy = -PH.JUMP; p.vx = dir * PH.RUN; p.jumpHeld = true; p.jumpBuf = 0; inp.jumpP = 0; p.airDash = true; ev(s, 'jump');
      return false;
    }
    if (inp.dash) { p.lastBolt = p.hangB; p.boltCD = PH.BOLT_CD; p.hangB = null; return false; }
    p.vx = 0; p.vy = 0; p.onGround = false; p.coyote = 0; p.airDash = true;
    return true;
  }
  if (p.zipB) {
    const b = p.zipB, tx = b.x + b.w / 2 - p.w / 2, ty = b.y + b.h / 2 + 3;
    const dx = tx - p.x, dy = ty - p.y, d = Math.hypot(dx, dy), ox = p.x, oy = p.y;
    if (d <= PH.ZIP_V) { moveX(s, dx); moveY(s, dy); } else { moveX(s, dx / d * PH.ZIP_V); moveY(s, dy / d * PH.ZIP_V); }
    p.vx = p.vy = 0;
    const moved = Math.hypot(p.x - ox, p.y - oy);
    if (Math.hypot(tx - p.x, ty - p.y) < 0.6) { p.zipB = null; p.hangB = b; p.airDash = true; p.pencil = true; p.onGround = false; ev(s, 'clank'); }
    else if (moved < Math.min(d, PH.ZIP_V) * 0.4 || --p.zipT <= 0) p.zipB = null;
    return true;
  }
  return false;
}
function onIce(s) {
  const p = s.p, ty = Math.floor((p.y + p.h + 0.5) / T);
  const a = tileAt(s, Math.floor(p.x / T), ty), b = tileAt(s, Math.floor((p.x + p.w - 0.001) / T), ty);
  const solidA = solidCode(s, a) || a === TL.ONEWAY, solidB = solidCode(s, b) || b === TL.ONEWAY;
  return (a === TL.ICE || b === TL.ICE) && (!solidA || a === TL.ICE) && (!solidB || b === TL.ICE);
}

/* story doors: with the library card, walking into one puts you at its partner, still moving */
function doorHit(p, d) { return Math.abs(p.x + p.w / 2 - (d.x + d.w / 2)) < 5 && p.y < d.y + d.h && p.y + p.h > d.y; }
function doorTouching(s) { for (const d of s.world.doors) if (doorHit(s.p, d)) return d; return null; }
function useDoors(s) {
  const p = s.p;
  if (p.doorLock && !doorHit(p, p.doorLock)) p.doorLock = null;
  if (!s.powers.card || p.doorLock || p.kb > 0) return;
  const d = doorTouching(s);
  if (!d || !d.to) return;
  const t = d.to;
  p.x = t.x + t.w / 2 - p.w / 2; p.y = t.y + t.h - p.h;
  p.doorLock = t; p.hangB = null; p.zipB = null; p.wallDir = 0; p.glide = false; p.dashT = 0; p.onGround = false;
  ev(s, 'door', t);
}

/* one fixed 60 Hz tick. inp: {l,r,jump,jumpP,erase,dash,flip} (…P / action flags are presses this tick) */
function step(s, inp) {
  const p = s.p, w = s.world;
  s.events.length = 0; s.frame++;
  if (s.won) return;
  if (s.dead > 0) { if (--s.dead === 0) respawn(s); return; }
  for (let i = s.plats.length - 1; i >= 0; i--) if (--s.plats[i].t <= 0) s.plats.splice(i, 1);
  updEnemies(s);
  if (s.freeze > 0) {
    if (--s.freeze === 0) { p.x = p.safeX; p.y = p.safeY; p.vx = p.vy = 0; p.dashT = 0; p.kb = 0; s.plats.length = 0; trackRoom(s); ev(s, 'return'); }
    return;
  }
  s.time++;
  if (p.inv > 0) p.inv--;
  if (p.dashCD > 0) p.dashCD--;
  if (p.eraseCD > 0) p.eraseCD--;
  if (p.landT > 0) p.landT--;
  if (inp.jumpP) p.jumpBuf = PH.BUFFER; else if (p.jumpBuf > 0) p.jumpBuf--;

  const dir = p.kb > 0 ? 0 : (inp.r ? 1 : 0) - (inp.l ? 1 : 0);
  const steer = p.kickT > 0 ? 0 : dir;
  if (steer && p.dashT === 0) p.face = steer;
  if (p.wallCoyote > 0) p.wallCoyote--;

  // fridge magnet: Dash near a metal bolt zips you to it; you hang there until you jump or zip on
  if (!magnet(s, inp, dir)) {
  // drop through: hold down while standing on a one-way ledge or a pencil line
  if (inp.down && p.kb === 0 && onOneWay(s)) {
    p.y += 1; p.onGround = false; p.coyote = 0; p.jumpBuf = 0; ev(s, 'drop');
  }
  // a downpour shoves you down: no jumping, climbing, gliding or drawing until you have the umbrella
  const soaked = !s.powers.umbrella && overlapsCode(s, p.x, p.y, p.w, p.h, TL.RAIN);
  p.soaked = soaked;

  // ink dash
  if (inp.dash && s.powers.dash && p.kb === 0) {
    if (p.dashT === 0 && p.dashCD === 0 && p.airDash) {
      p.dashT = PH.DASH_T; p.dashDir = p.wallDir ? -p.wallDir : (dir || p.face); p.face = p.dashDir; p.airDash = false; p.dashCD = PH.DASH_CD; p.jumpHeld = false;
      p.wallDir = 0; p.kickT = 0; p.glide = false;
      ev(s, 'dash', p.dashDir);
    } else ev(s, 'dashFail');
  }

  // horizontal speed
  if (p.dashT > 0) p.vx = p.dashDir * PH.DASH_V;
  else if (p.kb > 0) { p.kb--; p.vx *= 0.94; }
  else if (p.kickT > 0) p.kickT--;
  else if (p.glide) {
    const target = steer * PH.GLIDE_RUN;
    if (p.vx < target) p.vx = Math.min(target, p.vx + PH.GLIDE_ACC); else if (p.vx > target) p.vx = Math.max(target, p.vx - PH.GLIDE_ACC * 0.5);
  } else {
    const target = steer * PH.RUN;
    const icy = p.onGround && p.gk === 'tile' && onIce(s);
    const a = p.onGround ? (icy ? (steer ? PH.ICE_ACC : PH.ICE_DEC) : (steer ? PH.ACC : PH.DEC)) : (steer ? PH.AIRACC : PH.AIRDEC);
    if (p.vx < target) p.vx = Math.min(target, p.vx + a); else if (p.vx > target) p.vx = Math.max(target, p.vx - a);
  }

  // sticky tape: jump off a wall. Holding toward the wall hops up it; anything else leaps away.
  let drew = false;
  if (s.powers.tape && p.jumpBuf > 0 && !p.onGround && p.coyote === 0 && p.kb === 0 && !soaked) {
    let side = p.wallDir || (p.wallCoyote > 0 ? p.lastWall : 0);
    if (!side && p.dashT === 0) side = wallAt(s, 1) ? 1 : wallAt(s, -1) ? -1 : 0;
    if (side) {
      const climb = dir === side;
      p.vy = -(climb ? PH.CLIMB_VY : PH.WJ_VY); p.vx = -side * (climb ? PH.CLIMB_VX : PH.WJ_VX);
      p.kickT = climb ? PH.CLIMB_KICK : PH.WJ_KICK; p.face = -side;
      p.dashT = 0; p.wallDir = 0; p.wallCoyote = 0; p.glide = false; p.jumpBuf = 0; p.jumpHeld = false; drew = true; // wall hops are always full height, even on a quick tap
      ev(s, 'walljump', side); ev(s, 'jump');
    }
  }

  // pencil: jumping in midair draws a ledge under your feet and you stop on it; jump again to keep going
  const canDraw = s.powers.pencil && p.pencil && !p.onGround && p.coyote === 0 && p.kb === 0 && !p.wallDir && !drew && !soaked;
  if (inp.jumpP && canDraw) {
    s.plats.length = 0;
    s.plats.push({ x: p.x + p.w / 2 - PH.PLAT_W / 2, y: p.y + p.h, w: PH.PLAT_W, t: PH.PLAT_T, max: PH.PLAT_T });
    if (p.dashT > 0) { p.dashT = 0; p.vx = p.dashDir * PH.RUN; }
    p.pencil = false; p.jumpBuf = 0; p.jumpHeld = false; p.vy = 0; p.glide = false; drew = true;
    ev(s, 'draw');
  }

  // paper airplane: hold jump while falling to glide
  const wasGlide = p.glide;
  p.glide = s.powers.plane && inp.jump && !drew && !soaked && !p.onGround && !p.wallDir && p.dashT === 0 && p.kb === 0 && (p.glide || p.vy >= 0);
  if (p.glide && !wasGlide) ev(s, 'glide');
  const windy = overlapsCode(s, p.x + 2, p.y + 2, p.w - 4, p.h - 4, TL.WIND);

  // vertical speed
  if (p.dashT > 0) p.vy = 0;
  else if (drew) { /* already launched this tick */ }
  else if (p.wallDir) p.vy = Math.min(p.vy + PH.G, PH.CLING_SLIDE);
  else if (p.glide) p.vy = windy ? Math.max(p.vy - PH.WIND_LIFT, -PH.WIND_MAX) : Math.min(p.vy + PH.GLIDE_G, PH.GLIDE_FALL);
  else {
    if (p.jumpHeld && !inp.jump && p.vy < PH.JUMPCUT) p.vy = PH.JUMPCUT;
    if (p.vy >= 0) p.jumpHeld = false;
    p.vy = Math.min(p.vy + PH.G - (windy ? PH.WIND_SOFT : 0), PH.MAXFALL);
    if (p.jumpBuf > 0 && (p.onGround || p.coyote > 0) && p.kb === 0 && !soaked) {
      let v = PH.JUMP;
      if (s.powers.spring) {
        // spring shoes: a jump made right after landing on solid ground bounces one level higher
        const chain = p.onGround && p.gk === 'tile' && p.bounceOK && p.groundT <= PH.BOUNCE_WIN;
        p.bounce = chain ? Math.min(2, p.bounce + 1) : 0;
        v = PH.BOUNCE[p.bounce];
      }
      p.vy = -v; p.jumpBuf = 0; p.coyote = 0; p.jumpHeld = true; p.bounceOK = true; ev(s, 'jump', p.bounce || 0);
    }
  }

  if (soaked && p.vy < PH.RAIN_V) { p.vy = PH.RAIN_V; p.jumpHeld = false; }
  moveX(s, p.vx);
  const wasGround = p.onGround;
  moveY(s, p.vy);
  if (p.onGround) {
    p.groundT = wasGround ? p.groundT + 1 : 0;
    if (p.groundT > PH.BOUNCE_WIN) p.bounce = 0;
    p.coyote = PH.COYOTE; p.wallDir = 0; p.glide = false; p.kickT = 0;
    if (p.dashT === 0) p.airDash = true;
    if (p.gk === 'tile') p.pencil = true;
    if (!wasGround) { ev(s, 'land'); p.landT = 8; }
  } else { if (wasGround && p.vy >= 0) p.bounceOK = false; if (p.coyote > 0) p.coyote--; }
  if (p.dashT > 0 && --p.dashT === 0) p.vx = p.dashDir * PH.RUN;

  // sticky tape: cling to a wall you push against in the air, slide slowly, let go by pushing away
  if (s.powers.tape && !p.onGround && p.dashT === 0 && p.kb === 0 && p.kickT === 0) {
    if (p.wallDir) {
      const release = () => { p.lastWall = p.wallDir; p.wallCoyote = PH.WALL_COYOTE; p.wallDir = 0; };
      if (!wallAt(s, p.wallDir)) p.wallDir = 0;
      else if (dir === -p.wallDir) release();
      else if (dir === 0) { if (--p.clingT <= 0) release(); }
      else p.clingT = PH.CLING_GRACE;
    } else if (dir && p.vy > -1 && wallAt(s, dir)) {
      p.wallDir = dir; p.clingT = PH.CLING_GRACE; p.airDash = true; p.glide = false; p.vx = 0;
      if (p.vy > PH.CLING_SLIDE) p.vy = PH.CLING_SLIDE;
      ev(s, 'stick', dir);
    }
  } else if (p.wallDir) p.wallDir = 0;
  if (p.wallDir) p.face = -p.wallDir;
  } // end of normal movement (skipped while the magnet holds you)

  // eraser
  if (inp.erase && s.powers.erase && p.eraseCD === 0 && p.kb === 0) { p.eraseT = PH.ERASE_T; p.eraseCD = PH.ERASE_CD; ev(s, 'erase'); }
  if (p.eraseT > 0) {
    const b = eraseBox(p);
    const tx0 = Math.floor(b.x / T), tx1 = Math.floor((b.x + b.w - 0.001) / T), ty0 = Math.floor(b.y / T), ty1 = Math.floor((b.y + b.h - 0.001) / T);
    for (let ty = ty0; ty <= ty1; ty++) for (let tx = tx0; tx <= tx1; tx++) if (tileAt(s, tx, ty) === TL.SCRIBBLE) breakGroup(s, tx, ty, TL.SCRIBBLE);
    for (const e of s.enemies) if (!e.gone && hit(b, hurtBox(e))) { e.gone = true; e.squish = 24; ev(s, 'kill', e); }
    p.eraseT--;
  }

  // page flip
  if (inp.flip && s.powers.flip) tryFlip(s);

  updateSafe(s);

  // hazards
  const pr = { x: p.x, y: p.y, w: p.w, h: p.h };
  {
    const tx0 = Math.floor(p.x / T), tx1 = Math.floor((p.x + p.w - 0.001) / T), ty0 = Math.floor(p.y / T), ty1 = Math.floor((p.y + p.h - 0.001) / T);
    let spiked = false;
    for (let ty = ty0; ty <= ty1 && !spiked; ty++) for (let tx = tx0; tx <= tx1; tx++) if (tileAt(s, tx, ty) === TL.SPIKE && hit(pr, spikeBox(tx, ty))) { spiked = true; break; }
    if (spiked || p.y > w.H * T + 8) { hazard(s); return; }
  }
  // enemies
  if (p.inv === 0) for (const e of s.enemies) if (!e.gone && hit(pr, hurtBox(e))) { hurt(s, e.x + e.w / 2); if (s.dead) return; break; }

  // pickups
  for (const e of w.byRoom[s.room] || []) {
    if (!hit(pr, e)) continue;
    if (e.k === 'scrap' && !s.got.has('s' + e.id)) {
      s.got.add('s' + e.id); ev(s, 'scrap', e.id);
      if (scrapCount(s) >= w.scrapN && !s.done) { s.won = true; s.done = true; ev(s, 'win'); }
    } else if (e.k === 'power' && !s.powers[e.pw]) {
      s.powers[e.pw] = true; s.got.add(e.pw); ev(s, 'power', e.pw);
    } else if (e.k === 'pot' && s.powers.brush && p.color !== e.color) {
      // dip into the pot, unless that would leave you standing inside paint of your old color
      const old = p.color ? TL.PO + p.color - 1 : -1;
      if (old < 0 || !overlapsCode(s, p.x, p.y, p.w, p.h, old)) { p.color = e.color; ev(s, 'paint', e.color); }
    } else if (e.k === 'book') {
      if (s.book !== e.id) { s.book = e.id; ev(s, 'book', e.id); }
      if (p.hp < p.maxHp) { p.hp = p.maxHp; ev(s, 'heal'); }
    }
  }
  useDoors(s);
  trackRoom(s);
}

